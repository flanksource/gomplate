// Monaco's theme service probes `matchMedia` for the forced-colors setting as
// soon as the editor API module loads. jsdom does not implement it, so provide
// the minimum shape the probe needs.
if (typeof window !== "undefined" && typeof window.matchMedia !== "function") {
  window.matchMedia = ((query: string) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  })) as typeof window.matchMedia;
}
