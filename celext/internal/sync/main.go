// Command sync copies the selected cel-go extensions and applies the cost-model opt-out.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

const installMessage = "install the flanksource gopatch fork: git clone https://github.com/flanksource/gopatch && make -C gopatch install"

const workaround = `// WORKAROUND(cel-cost-model-compile): cel-go compiles overload cost models on every Env.configure;
// this copy lets callers that never estimate cost opt out of registering them.
// Correct fix: cel-go compiles cost models once per model set. Ref: discussed with user 2026-11-11.
`

var sourceFiles = []string{
	"strings.go", "encoders.go", "lists.go", "math.go", "sets.go",
	"guards.go", "formatting.go", "formatting_v2.go",
}

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	if err := os.Setenv("GOWORK", "off"); err != nil {
		return err
	}
	root, err := filepath.Abs("..")
	if err != nil {
		return err
	}
	binary := os.Getenv("GOPATCH")
	if binary == "" {
		binary = "gopatch"
	}
	binary, err = exec.LookPath(binary)
	if err != nil {
		return fmt.Errorf("%s: %w", installMessage, err)
	}
	module, err := commandOutput(root, "go", "list", "-m", "-f", "{{.Dir}} {{.Version}}", "cel.dev/cel-go")
	if err != nil {
		return err
	}
	module = strings.TrimSpace(module)
	separator := strings.LastIndexByte(module, ' ')
	if separator <= 0 || separator == len(module)-1 {
		return fmt.Errorf("invalid cel-go module directory/version: %q", module)
	}
	return syncSources(root, binary, module[:separator], module[separator+1:])
}

func syncSources(root, binary, source, version string) error {
	header := fmt.Sprintf("// Code generated by celext/internal/sync from cel.dev/cel-go@%s/ext. DO NOT EDIT.\n", version) + workaround + "\n"
	counts := make(map[string]int, len(sourceFiles))
	for _, name := range sourceFiles {
		data, err := copySource(filepath.Join(source, "ext", name), header)
		if err != nil {
			return err
		}
		counts[name] = bytes.Count(data, []byte("cel.CostModel("))
		if err := os.WriteFile(filepath.Join(root, "celext", name), data, 0o644); err != nil {
			return err
		}
	}
	versionFile := filepath.Join(root, "celext", "source_version.go")
	if err := os.WriteFile(versionFile, []byte(header+"package celext\n\n// SourceVersion is the cel-go version used to generate this package.\nconst SourceVersion = "+fmt.Sprintf("%q", version)+"\n"), 0o644); err != nil {
		return err
	}
	if err := rewrite(root, binary); err != nil {
		return err
	}
	return verify(root, counts, version)
}

func rewrite(root, binary string) error {
	for _, library := range []string{"stringLib", "encoderLib", "listsLib", "mathLib", "setsLib"} {
		if err := run(root, binary, "add", "field", library+".costs", "costModels", "./celext"); err != nil {
			return err
		}
	}
	if err := run(root, binary, "patch", "-p", "celext/internal/sync/sets-receiver.patch", "./celext"); err != nil {
		return err
	}
	for _, receiver := range []string{"*stringLib", "*encoderLib", "listsLib", "*mathLib", "setsLib"} {
		if err := run(root, binary, "replace", "method", receiver+".CompileOptions", "--package", "celext", "--match", `cel\.CostModel\(`, "--content", "lib.costs.costModel(", "./celext"); err != nil {
			return err
		}
	}
	return nil
}

func verify(root string, counts map[string]int, version string) error {
	total := 0
	for _, name := range append(append([]string{}, sourceFiles...), "source_version.go") {
		path := filepath.Join(root, "celext", name)
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if bytes.Contains(data, []byte("cel.CostModel(")) {
			return fmt.Errorf("%s: unpatched cel.CostModel call", path)
		}
		actual := bytes.Count(data, []byte("lib.costs.costModel("))
		if actual != counts[name] {
			return fmt.Errorf("%s: got %d cost-model calls, upstream has %d", path, actual, counts[name])
		}
		formatted, err := format.Source(data)
		if err != nil {
			return fmt.Errorf("%s: gofmt: %w", path, err)
		}
		if !bytes.Equal(data, formatted) {
			return fmt.Errorf("%s: output is not gofmt formatted", path)
		}
		total += actual
		fmt.Printf("celext/%s: %d cost-model calls verified; gofmt clean\n", name, actual)
	}
	fmt.Printf("celext: synced %s, %d upstream files, %d cost-model calls verified\n", version, len(sourceFiles), total)
	return nil
}

func run(root, binary string, args ...string) error {
	fmt.Printf("%s %s\n", binary, strings.Join(args, " "))
	output, err := commandOutput(root, binary, args...)
	fmt.Print(output)
	return err
}

func commandOutput(root, binary string, args ...string) (string, error) {
	command := exec.Command(binary, args...)
	command.Dir = root
	output, err := command.CombinedOutput()
	if err != nil {
		return string(output), fmt.Errorf("%s %s: %w\n%s", binary, strings.Join(args, " "), err, output)
	}
	return string(output), nil
}
